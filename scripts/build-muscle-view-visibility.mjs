import fs from 'node:fs';
import crypto from 'node:crypto';
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { MeshoptDecoder } from 'three/addons/libs/meshopt_decoder.module.js';
import { DIEGO_REGION_IDS, DIEGO_ASSET_REVISION, DIEGO_MODEL_FILE } from '../src/data/diegoAnatomy.js';

// Offline orthographic depth rendering of the approved mesh. These pixel counts
// describe visibility in this model, never muscle activation or exercise effects.
const bytes = fs.readFileSync(`public/anatomy/${DIEGO_MODEL_FILE}`);
const manifest = JSON.parse(fs.readFileSync('public/anatomy/diego-manifest.json'));
if (crypto.createHash('sha256').update(bytes).digest('hex') !== manifest.sha256) throw new Error('Unexpected anatomy asset');
const size = bytes.readUInt32LE(12);
const json = JSON.parse(bytes.subarray(20, 20 + size));
if (json.asset.extras.assetRevision !== DIEGO_ASSET_REVISION) throw new Error('Unexpected anatomy revision');
json.buffers[0].uri = 'data:application/octet-stream;base64,' + bytes.subarray(28 + size).toString('base64');
json.materials = json.materials.map(item => ({ name: item.name }));
delete json.images; delete json.textures; delete json.samplers;
globalThis.ProgressEvent = class { constructor(type, values) { this.type = type; Object.assign(this, values); } };
const { scene } = await new GLTFLoader().setMeshoptDecoder(MeshoptDecoder).parseAsync(JSON.stringify(json), '');
scene.updateMatrixWorld(true);
const meshes = [];
scene.traverse(object => { if (object.isMesh) meshes.push(object); });
const width = 240, height = 400, scale = height / 2.02;
const views = { front: 0, back: Math.PI, frontOblique: Math.PI / 4, backOblique: Math.PI * 3 / 4, side: Math.PI / 2 };
const visibility = Object.fromEntries(DIEGO_REGION_IDS.filter(id => id !== 'context')
  .map(id => [id, Object.fromEntries(Object.keys(views).map(view => [view, 0]))]));
for (const [view, angle] of Object.entries(views)) {
  const depth = new Float32Array(width * height).fill(-Infinity);
  const regions = new Int16Array(width * height).fill(-1);
  const cos = Math.cos(angle), sin = Math.sin(angle);
  for (const object of meshes) {
    const geometry = object.geometry, positions = geometry.getAttribute('position'), training = geometry.getAttribute('_training'), indices = geometry.getIndex();
    const point = new THREE.Vector3(), vertices = [];
    for (let index = 0; index < positions.count; index++) {
      point.fromBufferAttribute(positions, index).applyMatrix4(object.matrixWorld);
      const x = cos * point.x + sin * point.z, z = -sin * point.x + cos * point.z;
      const region = training ? (training.getZ(index) > 127.5 ? training.getY(index) : training.getX(index)) : 0;
      vertices.push([width / 2 + x * scale, (1.95 - point.y) * scale, z, region]);
    }
    for (let index = 0; index < (indices?.count ?? positions.count); index += 3) {
      const a = vertices[indices ? indices.getX(index) : index], b = vertices[indices ? indices.getX(index + 1) : index + 1], c = vertices[indices ? indices.getX(index + 2) : index + 2];
      const denominator = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1]);
      if (Math.abs(denominator) < 1e-7) continue;
      const left = Math.max(0, Math.floor(Math.min(a[0], b[0], c[0]))), right = Math.min(width - 1, Math.ceil(Math.max(a[0], b[0], c[0])));
      const top = Math.max(0, Math.floor(Math.min(a[1], b[1], c[1]))), bottom = Math.min(height - 1, Math.ceil(Math.max(a[1], b[1], c[1])));
      for (let y = top; y <= bottom; y++) for (let x = left; x <= right; x++) {
        const u = ((b[1] - c[1]) * (x + 0.5 - c[0]) + (c[0] - b[0]) * (y + 0.5 - c[1])) / denominator;
        const v = ((c[1] - a[1]) * (x + 0.5 - c[0]) + (a[0] - c[0]) * (y + 0.5 - c[1])) / denominator;
        const w = 1 - u - v;
        if (u < 0 || v < 0 || w < 0) continue;
        const z = u * a[2] + v * b[2] + w * c[2], pixel = y * width + x;
        if (z <= depth[pixel]) continue;
        depth[pixel] = z;
        regions[pixel] = u > v && u > w ? a[3] : v > w ? b[3] : c[3];
      }
    }
  }
  for (const region of regions) {
    const id = DIEGO_REGION_IDS[region];
    if (visibility[id]) visibility[id][view]++;
  }
}
fs.writeFileSync('src/data/muscleViewVisibility.js', `// Generated by scripts/build-muscle-view-visibility.mjs from the approved anatomy mesh.\n// Visible pixels per view, not physiological measurements.\nexport const MUSCLE_VIEW_ASSET_REVISION = '${DIEGO_ASSET_REVISION}';\nexport const MUSCLE_VIEW_VISIBILITY = ${JSON.stringify(visibility, null, 2)};\n`);
console.log(JSON.stringify({ revision: DIEGO_ASSET_REVISION, regions: Object.keys(visibility).length }));
